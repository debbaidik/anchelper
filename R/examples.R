#' Worked examples: control charts (Control Charts 1 + Problem Set 2), solved with qcc
#' @param topic optional, one or more of: "choose", "cc1_1", "cc1_2", "cc1_3", "cc1_4",
#'   "cc1_5", "ps2_1", "ps2_2".
#'   cc1_* = paper 'Control Charts 1' (attribute charts);
#'   ps2_* = paper 'Problem Set 2' (continuous variables).
#'   NULL lists all.
#' @export
examples <- function(topic = NULL) {
  f <- list(
    choose = c(
      "CHOOSING THE TYPE OF CHART",
      "  Q1. Measurement (length, strength) or count?",
      "      measurement          -> xbar with R or S chart (variable data)",
      "      count of defectives  -> p or np chart  (binomial; each unit good/bad, d_i <= n_i)",
      "      count of defects     -> c or u chart   (Poisson; a unit can have many defects, c_i can exceed n_i)",
      "  Q2. Is the inspection unit / sample size constant?",
      "                     constant size    variable size",
