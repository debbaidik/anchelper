      "      defects        c                u  (u_i = c_i/n_i, variable-width limits)",
      "  Wording clue: 'non-conforming / defective units' -> p ; 'number of defects' -> c or u",
      "  Check: if 'defects' > units inspected in some row, p is impossible (p would exceed 1) -> u chart",
      "  c chart limits : cbar -/+ 3*sqrt(cbar)  (Poisson: mean = variance, no separate sigma estimate)",
