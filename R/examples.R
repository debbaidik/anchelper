      "    pbar = 102/2850 = 0.0358 ;  UCL = 0.0813 ;  LCL = 0",
      "    all remaining points inside (sample 20, p = 0.080, is close to UCL)",
      "  Comment: find and remove the assignable cause for sample 12, then use the revised limits.",
      "    LCL = 0, so the chart cannot signal improvement; sample 13 (0 defectives) is chance, not a signal"),
    cc1_2 = c(
      "CC1 Q2: p CHART, VARIABLE SUBGROUP SIZE, m = 10 days",
